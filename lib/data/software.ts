function toSoftware(r: Entry, i: number): Software {
  const quoted = r.price === undefined;
  return {
    id: `sw_${String(i + 1).padStart(2, "0")}`,
    slug: r.slug,
    name: r.name,
    vendor: r.vendor,
    sector: r.sector,
    summary: r.summary,
    website_url: r.site,
    vendor_website: r.host,
    affiliate_url: r.sage ? SAGE_AFFILIATE_URL : null,
    founded: r.founded ?? null,
    starting_price: quoted ? null : r.price!,
    price_currency: r.currency ?? null,
    price_basis: r.basis ?? null,
    price_checked_at: r.checked,
    pricing_plans: r.plans,
    pricing_note: r.note ?? null,
    free_trial: r.trial ?? null,
    free_plan: r.freePlan ?? null,
    demo: r.demo ?? null,
    compliance: r.compliance ?? null,
    bank_feeds: r.banks ?? null,
    features: r.features,
    integrations: r.integrations ?? [],
    assessment: null,
    logo: LOGOS[r.slug]?.src ?? null,
    screenshots: (SCREENSHOTS[r.slug] ?? []).map((shot) => shot.src),
    status: "active",
  };
}

export const SOFTWARE: Software[] = ROWS.map(toSoftware);
