/**
 * The register.
 *
 * Every figure here was read from the vendor's own page. Prices are what the
 * vendor lists, in the vendor's currency: rand on the South African pages of
 * Sage, Xero, QuickBooks, Zoho Books, SimplePay and Smartsheet, and dollars or
 * pounds where the vendor sells in no other currency. The site converts those to
 * rand for display. Each entry carries the date its price was read.
 *
 * Something is recorded only when a vendor page states it. A trial, a free plan,
 * a bank feed or a SARS return that the vendor does not mention is left out, so
 * the site never claims it. A product that publishes no price is quoted on
 * request, and its entry says what the vendor's page offers instead.
 *
 * Prices read on 2026-10-11 unless an entry carries another date. Two products
 * from the first build, Payroll Online and HR Companion, are not here: no vendor
 * website, price or product page could be found for either, so there was nothing
 * real to record.
 */

interface Entry {
  slug: string;
  name: string;
  vendor: string;
  sector: SectorSlug;
  /** One or two sentences on what the product is. */
  summary: string;
  site: string;
  /** The page the price was read from, without the scheme. */
  host: string;
  founded?: number;
  /** The lowest price on the vendor's page. undefined means quoted on request. 0 means free. */
  price?: number;
  currency?: Currency;
  basis?: PriceBasis;
  /** The date the price, or the absence of one, was read. */
  checked: string;
  plans: PricingPlan[];
  note?: string;
  trial?: boolean;
  freePlan?: boolean;
  demo?: boolean;
  features: string[];
  integrations?: string[];
  compliance?: string[];
  banks?: string[];
  sage?: boolean;
}

