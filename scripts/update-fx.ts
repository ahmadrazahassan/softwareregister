/**
 * Refreshes the saved exchange rate snapshot used when the live rate cannot be fetched.
 *
 *   npm run fx
 *
 * Source: the European Central Bank's daily reference rates, published through
 * Frankfurter (frankfurter.dev). They are reference rates, not a bank's dealing
 * rate, so a converted price is shown with a leading ≈ and with the rate and date.
 */
import fs from "node:fs";
import path from "node:path";

async function main() {
  const res = await fetch("https://api.frankfurter.dev/v1/latest?base=ZAR&symbols=USD,GBP,EUR");
  if (!res.ok) throw new Error(`Frankfurter answered ${res.status}`);
  const j = (await res.json()) as { date: string; rates: Record<string, number> };
  for (const c of ["USD", "GBP", "EUR"]) if (!(j.rates[c] > 0)) throw new Error(`No rate for ${c}`);

  const out =
    `/**\n * GENERATED by scripts/update-fx.ts. Run \`npm run fx\` to refresh it.\n *\n` +
    ` * The last saved exchange rates, used only when the live rate cannot be fetched.\n * perRand is how much of each currency one rand buys.\n */\n` +
    `import type { FxRates } from "../fx";\n\n` +
    `export const FX_SNAPSHOT: FxRates = {\n  asOf: "${j.date}",\n  source: "European Central Bank reference rates, via Frankfurter",\n  live: false,\n  perRand: { USD: ${j.rates.USD}, GBP: ${j.rates.GBP}, EUR: ${j.rates.EUR} },\n};\n`;
  fs.writeFileSync(path.resolve("lib/data/fx.ts"), out);
  console.log(`saved ${j.date}: R${(1 / j.rates.USD).toFixed(2)} per USD, R${(1 / j.rates.GBP).toFixed(2)} per GBP, R${(1 / j.rates.EUR).toFixed(2)} per EUR`);
}

main();
